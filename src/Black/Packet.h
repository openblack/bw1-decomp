class GPacket
{
public:
	// TODO: The original physics alternative is anonymous (Mac @class$5822).
	struct PhysicsData
	{
		LHPoint Position;
		LHPoint Velocity;
		LHPoint Direction;
		LHPoint Rotation;
		// BW1W120 0054b8f0
		PhysicsData()
		{
			Velocity.x = Velocity.y = Velocity.z = 0.0f;
			Rotation.x = Rotation.y = Rotation.z = 0.0f;
		}
	};
	uint8_t  field_0x0;
	uint8_t  Type;
	uint16_t SpeechData;
	uint32_t CheckSum;
	// Both original compilers construct every anonymous-union alternative.
	// Anonymous type numbers in the Mac symbols confirm this nesting. Member names
	// are descriptive; scalar-only packet alternatives are still represented by Bytes.
	union {
		struct
		{
			uint32_t ObjectIndex;
			int32_t  ObjectUniqueId;
			union {
				struct
				{
					union {
						struct
						{
							GestureSystemPacketData GestureData;
						};
					};
				};
				struct
				{
					union {
						struct
						{
							MapCoords Position;
						};
					};
				};
				struct
				{
					LHPoint HandPosition;
					LHPoint HandVelocity;
					LHPoint HandDirection;
					LHPoint HandUp;
					uint8_t Sequence;
				};
				struct
				{
					MapCoords Coords;
				};
				struct
				{
					MusicMoodPacket Music;
				};
				struct
				{
					uint32_t Argument;
					uint32_t Value;
				};
				struct
				{
					uint8_t Length;
					uint8_t Bytes[0xff];
				};
				struct
				{
					float FloatValue;
				};
			};
		};
		struct
		{
			int16_t ShortX;
			int16_t ShortZ;
			int32_t LongValue;
		};
		struct
		{
			uint16_t CellX;
			uint16_t CellZ;
			union {
				int32_t InfoType;
				int32_t Count;
				struct
				{
					uint16_t FirstShort;
					uint16_t SecondShort;
				};
			};
		};
		struct
		{
			PhysicsData Physics;
		};
		struct
		{
			MapCoords Start;
			MapCoords End;
		};
	};
	// BW1W120 0063c3f0 BW1M119 01119400
	void SendObjectIndex(unsigned long index);
	// BW1W120 0063c420 BW1M119 01011b40
	void ProcessPacket(uint8_t player_number);
	// BW1W120 0063df70 BW1M119 inlined
	GameThingWithPos* GetObjectFromIndex();
};

